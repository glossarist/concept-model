# frozen_string_literal: true

require "rdf/turtle"
require "yaml"
require "set"

module Glossarist
  module ConceptModel
    # ShaclGenerator — generates ontologies/shapes/glossarist.shacl.ttl from
    # the same SSOTs that drive the rest of the artifact chain:
    #
    #   1. ontologies/glossarist.ttl   — classes, properties, rdfs:domain,
    #      rdfs:range (drives sh:targetClass, sh:path, sh:datatype, sh:class)
    #   2. ontologies/prefixes.ttl     — canonical prefix bindings
    #   3. ontologies/shapes/shacl-model.yml — the SHACL-specific constraint
    #      layer OWL cannot express: cardinalities, sh:valuesFrom scheme
    #      bindings, sh:in enumerations, SPARQL constraints, severities,
    #      node co-types (skos/skosxl), external (non-gloss) paths, and
    #      per-shape omission declarations.
    #
    # Every OWL property whose rdfs:domain includes a shaped class is
    # emitted as a sh:property on that class's NodeShape unless the model
    # explicitly omits it — so ontology changes propagate to the shapes by
    # regeneration, and intentional exclusions stay visible and reviewed.
    #
    # Usage:
    #   bundle exec exe/generate-shacl          # regenerate committed file
    #   bundle exec exe/generate-shacl --check  # fail if committed drifts
    #
    # Output is committed for review; CI runs --check to catch drift
    # (same pattern as generate-types-from-schemas).
    class ShaclGenerator
      GLOSS_NS      = "https://www.glossarist.org/ontologies/".freeze
      MODEL_PATH    = Repo::ROOT / "ontologies/shapes/shacl-model.yml"
      PREFIXES_PATH = Repo::ROOT / "ontologies/prefixes.ttl"

      RDF_TYPE   = RDF::URI("http://www.w3.org/1999/02/22-rdf-syntax-ns#type").freeze
      OWL_DOMAIN = RDF::URI("http://www.w3.org/2000/01/rdf-schema#domain").freeze
      OWL_RANGE  = RDF::URI("http://www.w3.org/2000/01/rdf-schema#range").freeze
      OWL_UNION  = RDF::URI("http://www.w3.org/2002/07/owl#unionOf").freeze
      RDF_FIRST  = RDF::URI("http://www.w3.org/1999/02/22-rdf-syntax-ns#first").freeze
      RDF_REST   = RDF::URI("http://www.w3.org/1999/02/22-rdf-syntax-ns#rest").freeze
      RDF_NIL    = RDF::URI("http://www.w3.org/1999/02/22-rdf-syntax-ns#nil").freeze

      # OWL property types whose rdfs:domain/rdfs:range participate in
      # shape derivation.
      PROPERTY_TYPES = %w[
        http://www.w3.org/2002/07/owl#DatatypeProperty
        http://www.w3.org/2002/07/owl#ObjectProperty
        http://www.w3.org/2002/07/owl#TransitiveProperty
      ].map { |u| RDF::URI(u) }.freeze

      XSD_NS      = "http://www.w3.org/2001/XMLSchema#".freeze
      RDF_NS      = "http://www.w3.org/1999/02/22-rdf-syntax-ns#".freeze
      LANG_STRING = "#{RDF_NS}langString".freeze

      HEADER = <<~HEADER
        # Glossarist SHACL Shapes
        #
        # AUTO-GENERATED by exe/generate-shacl — DO NOT EDIT.
        # Sources of truth:
        #   - ontologies/glossarist.ttl           (classes, properties, domains, ranges)
        #   - ontologies/shapes/shacl-model.yml   (SHACL constraint layer)
        #   - ontologies/prefixes.ttl             (prefix bindings)
        # Regenerate with: bundle exec exe/generate-shacl
        # CI gate:         bundle exec exe/generate-shacl --check
      HEADER

      Section   = Struct.new(:title, :shapes, keyword_init: true)
      Shape     = Struct.new(:name, :target_class, :target_subjects_of, :cotypes,
                             :severity, :message, :note, :paths, :sparql, :or_constraints,
                             :omitted, keyword_init: true)
      PathShape = Struct.new(:path, :datatype, :klass, :min_count, :max_count, :values_from,
                             :in_values, :has_value, :severity, :comment, :note, :derived,
                             keyword_init: true)

      def initialize(check_mode: false, output: nil)
        @check_mode = check_mode
        @output_path = Pathname.new(output || Repo::SHACL.to_s)
        @warnings = []
        @shape_count = 0
        @path_count = 0
      end

      attr_reader :warnings

      # Runs the generator; returns exit code (0 success, 1 drift/error).
      def run
        rendered = render
        if @check_mode
          committed = File.read(@output_path)
          if committed == rendered
            $stdout.puts "OK: #{@output_path} is up to date " \
                         "(#{@shape_count} shapes, #{@path_count} property shapes)"
            0
          else
            $stderr.puts "FAIL: #{@output_path} has drifted from the model sources."
            $stderr.puts "  Regenerate with: bundle exec exe/generate-shacl"
            1
          end
        else
          File.write(@output_path, rendered)
          $stdout.puts "OK: wrote #{@output_path} " \
                       "(#{@shape_count} shapes, #{@path_count} property shapes)"
          warnings.each { |w| $stdout.puts "WARN: #{w}" }
          0
        end
      end

      # Renders the full Turtle artifact as a string (deterministic).
      def render
        @shape_count = 0
        @path_count = 0
        rendered = HEADER.dup
        rendered << prefix_block
        build.each { |section| rendered << render_section(section) }
        rendered
      end

      # Renders and returns the accumulated warnings (YAML-declared gloss
      # paths that glossarist.ttl does not declare).
      def warnings_after_render
        render
        warnings
      end

      private

      # ── Model building ────────────────────────────────────────────────

      def build
        onto = load_graph(Repo::ONTOLOGY.to_s)
        @props = extract_properties(onto)
        @model = YAML.safe_load_file(MODEL_PATH, aliases: true)

        @model.fetch("sections").map do |section|
          Section.new(
            title: section.fetch("title"),
            shapes: section.fetch("shapes").map { |name| build_shape(name) },
          )
        end
      end

      def build_shape(name)
        decl = @model.fetch("shapes").fetch(name) do
          raise KeyError, "shacl-model.yml: no declaration for shape #{name}"
        end
        declared = declared_paths(decl)
        derived = derive_paths(decl, declared)
        omitted = omission_map(decl)

        Shape.new(
          name: name,
          target_class: decl["target_class"],
          target_subjects_of: decl["target_subjects_of"],
          cotypes: Array(decl["cotypes"]),
          severity: decl["severity"],
          message: decl["message"],
          note: decl["note"],
          paths: declared + derived,
          sparql: decl["sparql"],
          or_constraints: decl["or"],
          omitted: omitted,
        ).tap do |s|
          @shape_count += 1
          @path_count += s.paths.length
        end
      end

      # omissions: {path => reason} — OWL properties with this shape's
      # target class in rdfs:domain that are intentionally NOT shaped.
      def omission_map(decl)
        (decl["omit"] || {}).to_h { |k, v| [k.to_s, v] }
      end

      # Paths fully declared in the model YAML — external (non-gloss) paths,
      # OWL-divergent overrides, and gloss paths OWL does not declare.
      def declared_paths(decl)
        Array(decl["paths"]).map do |path, extras|
          extras ||= {}
          expanded = expand_gloss(path)
          if expanded.start_with?(GLOSS_NS) && !@props.key?(expanded)
            @warnings << "shacl-model.yml: path #{path} on #{decl['target_class'] || decl['target_subjects_of']} " \
                         "is not declared in glossarist.ttl"
          end
          # datatype/class fall back to the OWL range unless explicitly
          # overridden on the declared path; an explicit class_ excludes the
          # datatype fallback and vice versa (a range is one or the other).
          prop = @props[expanded]
          fallback_dt, fallback_class = owl_range_types(prop)
          fallback_dt = nil if extras["class_"]
          fallback_class = nil if extras["datatype"]
          PathShape.new(
            path: path,
            datatype: extras["datatype"] || fallback_dt,
            klass: extras["class_"] || fallback_class,
            min_count: extras["min_count"],
            max_count: extras["max_count"],
            values_from: extras["values_from"],
            in_values: extras["in"],
            has_value: extras["has_value"],
            severity: extras["severity"],
            comment: extras["comment"],
            note: extras["note"],
            derived: false,
          )
        end
      end

      # Derives property shapes from the OWL ontology: every property whose
      # rdfs:domain includes the shape's target class, minus paths already
      # declared in the model YAML and explicit omissions. Shapes may opt
      # out with `derive: false` (constraint-only shapes that share a
      # target class with a primary shape).
      def derive_paths(decl, declared)
        target = decl["target_class"]
        return [] unless target
        return [] if decl["derive"] == false

        declared_set = declared.map(&:path).to_set
        omit_set = (decl["omit"] || {}).keys.map(&:to_s).to_set

        @props.values
              .select { |p| p[:domains].include?(expand_gloss(target)) }
              .reject { |p| declared_set.include?(p[:path_short]) || omit_set.include?(p[:path_short]) }
              .sort_by { |p| p[:path_short] }
              .map { |p| derived_path_shape(p) }
      end

      def derived_path_shape(prop)
        overrides = @model.dig("path_overrides", prop[:path_short]) || {}
        range_is_datatype = datatype_range?(prop[:range])

        PathShape.new(
          path: prop[:path_short],
          datatype: overrides["datatype"] || (range_is_datatype ? compact(prop[:range]) : nil),
          klass: overrides["class_"] || (range_is_datatype ? nil : compact(prop[:range])),
          min_count: overrides["min_count"],
          max_count: overrides["max_count"],
          values_from: overrides["values_from"],
          in_values: overrides["in"],
          has_value: overrides["has_value"],
          severity: overrides["severity"],
          comment: overrides["comment"],
          note: overrides["note"],
          derived: true,
        )
      end

      def datatype_range?(range)
        return false unless range.is_a?(String)
        range.start_with?(XSD_NS) || range == LANG_STRING
      end

      # Returns [datatype, class] for an OWL property record.
      def owl_range_types(prop)
        return [nil, nil] unless prop
        if datatype_range?(prop[:range])
          [compact(prop[:range]), nil]
        else
          [nil, compact(prop[:range])]
        end
      end

      def expand_gloss(path)
        path.sub(/^gloss:/, GLOSS_NS)
      end

      def compact(iri)
        return iri unless iri.is_a?(String)
        prefix_map.each do |pfx, ns|
          return "#{pfx}:#{iri.delete_prefix(ns)}" if iri.start_with?(ns)
        end
        iri.start_with?("http") ? "<#{iri}>" : iri
      end

      # prefix => namespace map parsed from prefixes.ttl (longest namespace
      # wins so overlapping namespaces compact correctly).
      def prefix_map
        @prefix_map ||= File.read(PREFIXES_PATH)
                            .scan(/^@prefix\s+(\S+):\s+<([^>]+)>\s*\.$/)
                            .map { |pfx, ns| [pfx, ns] }
                            .sort_by { |_, ns| -ns.length }
                            .to_h
      end

      # ── OWL extraction ────────────────────────────────────────────────

      def load_graph(path)
        repo = RDF::Repository.new
        RDF::Reader.open(path) { |r| r.each_statement { |s| repo << s } }
        repo
      end

      def extract_properties(onto)
        props = {}
        PROPERTY_TYPES.each do |type|
          onto.query([nil, RDF_TYPE, type]).each do |st|
            iri = st.subject.to_s
            next unless iri.start_with?(GLOSS_NS)
            props[iri] = {
              path_short: "gloss:#{iri.delete_prefix(GLOSS_NS)}",
              domains: domain_classes(onto, st.subject).sort,
              range: range_of(onto, st.subject),
            }
          end
        end
        props
      end

      def domain_classes(onto, prop)
        onto.query([prop, OWL_DOMAIN, nil]).flat_map do |st|
          union = onto.query([st.object, OWL_UNION, nil]).first
          union ? rdf_list_items(onto, union.object) : [st.object.to_s]
        end.uniq
      end

      def range_of(onto, prop)
        onto.query([prop, OWL_RANGE, nil]).first&.object&.to_s
      end

      def rdf_list_items(onto, node)
        items = []
        cur = node
        loop do
          first = onto.query([cur, RDF_FIRST, nil]).first
          break unless first
          items << first.object.to_s
          rest = onto.query([cur, RDF_REST, nil]).first
          break if rest.nil? || rest.object == RDF_NIL
          cur = rest.object
        end
        items
      end

      # ── Rendering ─────────────────────────────────────────────────────

      def prefix_block
        prefixes = File.read(PREFIXES_PATH)
                       .scan(/^@prefix\s+(\S+):\s+<([^>]+)>\s*\.$/)
        out = +"\n"
        prefixes.each { |pfx, ns| out << "@prefix #{(pfx + ':').ljust(10)} <#{ns}> .\n" }
        "#{out}\n"
      end

      def render_section(section)
        rule = "═" * 76
        banner = "# #{rule}\n# #{section.title}\n# #{rule}\n\n"
        banner + section.shapes.map { |s| render_shape(s) }.join("\n")
      end

      def render_shape(shape)
        clauses = []
        clauses << "sh:targetClass #{shape.target_class}" if shape.target_class
        clauses << "sh:targetSubjectsOf #{shape.target_subjects_of}" if shape.target_subjects_of
        clauses.concat(shape.cotypes.map { |c| "sh:class #{c}" })
        clauses << "sh:severity #{shape.severity}" if shape.severity
        clauses << %(sh:message "#{escape(shape.message)}"@en) if shape.message
        shape.paths.each { |p| clauses << render_path(p) }
        clauses << render_or(shape.or_constraints) if shape.or_constraints
        clauses.concat(render_sparql(shape.sparql)) if shape.sparql

        lines = []
        lines << "# #{shape.note}" if shape.note
        lines << "gloss:#{shape.name} a sh:NodeShape ;"
        lines.concat(
          clauses.each_with_index.map do |clause, i|
            body = clause.chomp
            i == clauses.length - 1 ? "  #{body} ." : "  #{body} ;"
          end,
        )
        shape.omitted.each do |path, reason|
          lines << "# not shaped: #{path} — #{reason}"
        end
        "#{lines.join("\n")}\n"
      end

      def render_path(p)
        inner = ["sh:path #{p.path}"]
        inner << "sh:datatype #{p.datatype}" if p.datatype
        inner << "sh:class #{p.klass}" if p.klass
        inner << "sh:minCount #{p.min_count}" if p.min_count
        inner << "sh:maxCount #{p.max_count}" if p.max_count
        if p.values_from
          iri = p.values_from.start_with?("http") ? p.values_from : "#{GLOSS_NS}#{p.values_from}"
          inner << "sh:valuesFrom <#{iri}>"
        end
        inner << "sh:in ( #{Array(p.in_values).map { |v| quote_if_literal(v) }.join(' ')} )" if p.in_values
        inner << "sh:hasValue #{p.has_value}" if p.has_value
        inner << "sh:severity #{p.severity}" if p.severity
        inner << %(rdfs:comment "#{escape(p.comment)}"@en) if p.comment
        body = "[\n#{inner.map { |l| "    #{l} ;\n" }.join}  ]"
        p.note ? "# #{p.note}\n  sh:property #{body}" : "sh:property #{body}"
      end

      def quote_if_literal(value)
        value.start_with?("<") ? value : "\"#{value}\""
      end

      def render_or(constraints)
        arms = constraints.map do |arm|
          inner = arm.map do |path, extras|
            segments = ["sh:path #{path}"]
            segments << "sh:minCount #{extras['min_count']}" if extras["min_count"]
            "[ sh:property [ #{segments.join(' ; ')} ] ]"
          end
          inner.join("\n    ")
        end
        "sh:or (\n    #{arms.join("\n    ")}\n  )"
      end

      def render_sparql(blocks)
        blocks.map do |block|
          inner = []
          inner << "a #{block['type']}" if block["type"]
          inner << %(sh:message "#{escape(block['message'])}"@en) if block["message"]
          if block["prefixes"]
            decls = block["prefixes"].map do |pfx, ns|
              %(sh:declare [ sh:prefix "#{pfx}" ; sh:namespace "#{ns}"^^xsd:anyURI ])
            end
            inner << "sh:prefixes [\n      #{decls.join(" ;\n      ")}\n    ]"
          end
          # The stored block scalar holds the query left-flushed; the
          # historical Turtle literal carries 6-space indentation:
          # "\n      <line>...\n    ".
          query = block["select"].chomp.lines.map(&:rstrip)
                                 .map { |l| l.empty? ? l : "      #{l}" }.join("\n")
          inner << %(sh:select\n    """\n#{query}\n    """)
          "sh:sparql [\n    #{inner.join(" ;\n    ")}\n  ]"
        end
      end

      def escape(text)
        text.to_s.gsub("\\", "\\\\").gsub('"', '\\"')
      end
    end
  end
end
